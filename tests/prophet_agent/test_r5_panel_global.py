"""Panel centres from the pooled model (global_gbm, global_blend) and the panel total.

Synthetic: every series here is generated by _values (a trend and a weekly wave), and the TimesFM engine is a fake that
forecasts the last value plus 1.0 with a band of plus or minus 2. No real data and no real model are used; the packs are
built in the real sandbox.
"""
from __future__ import annotations

import json

import numpy as np
import pytest

from prophet_agent.forecast import timesfm as timesfm_mod
from prophet_agent.forecast.global_gbm import global_forecast
from prophet_agent.forecast.types import Forecast
from prophet_agent.tools import report_tool as rt
from prophet_agent.tools import series_io

RUN = "d" * 32
N, H = 120, 4


class PanelEngine:
    checkpoint = "stub"
    global_context = 64

    def forecast_batch(self, series_list, horizon):
        point = np.stack([np.full(horizon, float(np.asarray(s)[-1]) + 1.0) for s in series_list])
        return Forecast(point, np.repeat(point[:, :, None], 9, axis=2) + np.linspace(-2, 2, 9))


@pytest.fixture(autouse=True)
def fake_engine(monkeypatch):
    monkeypatch.setattr(timesfm_mod.TimesFMEngine, "get", classmethod(lambda cls: PanelEngine()))


def _values(offset: float, n: int = N) -> list[float]:
    return [round(50 + offset + 0.1 * i + 3 * np.sin(2 * np.pi * i / 7), 4) for i in range(n)]


@pytest.fixture
def sandbox(tmp_path, monkeypatch):
    """A sandbox root under tmp_path holding three synthetic stations, so no real data is read."""
    monkeypatch.setattr(series_io, "SANDBOX_ROOT", tmp_path)
    out = tmp_path / RUN / "out"
    out.mkdir(parents=True)
    stations = {"Station A": _values(0), "Station B": _values(10), "Station C": _values(20)}
    (out / "series.json").write_text(json.dumps({"series": stations}))
    return stations


def _args(**kw):
    base = {"source": {"run_id": RUN, "file": "out/series.json"}, "horizon": H, "title": "Synthetic panel"}
    base.update(kw)
    return base


def _pooled(stations: dict) -> dict:
    return global_forecast({n: np.asarray(v, dtype=float) for n, v in stations.items()}, H, season=None)


def test_global_gbm_centre_points_equal_the_pooled_models_points(sandbox):
    out = rt._run(_args(centre="global_gbm"), "k")
    pooled = _pooled(sandbox)
    for name, fc in out["forecast"]["series"].items():
        assert fc["centre"] == {"rule": "global_gbm"}
        assert fc["point"] == pytest.approx(pooled[name]["point"], abs=1e-4)
        assert fc["quantiles"]["0.1"] == pytest.approx(pooled[name]["q10"], abs=1e-4)
        assert fc["quantiles"]["0.9"] == pytest.approx(pooled[name]["q90"], abs=1e-4)
        assert "health" in fc and len(fc["quantiles"]) == 9


def test_global_blend_points_are_the_mean_of_timesfm_and_the_pooled_model(sandbox):
    out = rt._run(_args(centre="global_blend"), "k")
    pooled = _pooled(sandbox)
    for name, fc in out["forecast"]["series"].items():
        assert fc["centre"] == {"rule": "global_blend"}
        tfm = np.full(H, sandbox[name][-1] + 1.0)              # the fake engine's point for each series
        assert np.asarray(fc["timesfm_point"]) == pytest.approx(tfm, abs=1e-4)
        assert fc["point"] == pytest.approx(0.5 * (tfm + np.asarray(pooled[name]["point"])), abs=1e-4)
        # the fake band is the point plus or minus 2 at the 0.1 and 0.9 levels, so the blend's 0.1 is the mean of the two
        assert fc["quantiles"]["0.1"] == pytest.approx(0.5 * (tfm - 2.0 + np.asarray(pooled[name]["q10"])), abs=1e-4)


def test_per_series_dict_still_refuses_the_pooled_centres(sandbox):
    with pytest.raises(ValueError, match="must be one of"):
        rt._run(_args(centre={"Station A": "global_gbm"}), "k")
    with pytest.raises(ValueError, match="must be one of"):
        rt._run(_args(centre={"Station B": "global_blend"}), "k")


def test_a_single_series_still_refuses_the_pooled_centres():
    with pytest.raises(ValueError, match="centre must be one of"):
        rt._run({"values": _values(0), "horizon": H, "title": "One", "centre": "global_gbm"}, "k")


def test_panel_total_centre_is_the_sum_of_the_entities_point_sums(sandbox):
    out = rt._run(_args(centre="global_gbm"), "k")
    total = out["panel_total"]
    expected = sum(sum(fc["point"]) for fc in out["forecast"]["series"].values())
    assert total["centre"] == pytest.approx(expected, abs=0.02)
    assert total["steps"] == H
    assert set(total["if_entities_miss_independently"]) == {"q10", "q90"}
    assert set(total["if_entities_miss_together"]) == {"q10", "q90"}
    assert "lies between" in total["note"]


def test_the_independent_panel_bound_is_strictly_narrower_than_the_together_bound(sandbox):
    total = rt._run(_args(centre="global_blend"), "k")["panel_total"]
    ind, tog = total["if_entities_miss_independently"], total["if_entities_miss_together"]
    assert tog["q90"] - tog["q10"] > 0
    assert ind["q90"] - ind["q10"] < tog["q90"] - tog["q10"]
    assert ind["q10"] < total["centre"] < ind["q90"]


def test_observe_carries_the_panel_total_and_the_centre_rule(sandbox):
    out = rt._run(_args(centre="global_gbm"), "k")
    view = rt.observe(out)
    assert view["panel_total"] == out["panel_total"]
    assert all(line["centre"] == "global_gbm" for line in view["series"].values())


def test_blend_on_a_panel_is_the_pooled_blend(sandbox):
    # live electricity rep10 (2026-11-23): panel_backtest ranked "blend" (pooled model + TimesFM); the pack refused "blend"
    # twice, fell back to TimesFM, and the answer still named the blend as the centre line
    out = rt._run(_args(centre="blend"), "k")
    ref = rt._run(_args(centre="global_blend"), "k")
    for name, fc in out["forecast"]["series"].items():
        assert fc["centre"] == {"rule": "global_blend"}
        assert fc["point"] == pytest.approx(ref["forecast"]["series"][name]["point"], abs=1e-6)


def test_a_per_series_blend_on_a_panel_names_the_whole_panel_form(sandbox):
    with pytest.raises(ValueError, match="as one string"):
        rt._run(_args(centre={"Station A": "blend"}), "k")


def test_the_accuracy_facts_name_the_drawn_centre_and_both_total_bounds():
    from prophet_agent.runtime.contracts import panel_sentence, trust_statement
    series = {f"MT_{i:03d}": {"centre": "timesfm"} for i in range(1, 4)}
    pt = {"centre": 4375772.9, "steps": 7, "if_entities_miss_independently": {"q10": 4320869.3, "q90": 4430676.6},
          "if_entities_miss_together": {"q10": 3871340.6, "q90": 5089679.0}}
    hist = [{"kind": "tool", "tool": "forecast_report", "result": {"n_series": 3, "series": series, "panel_total": pt}}]
    s = panel_sentence(hist)
    assert "TimesFM for all 3 series" in s
    assert "4,320,869 to 4,430,677 if the series miss independently" in s
    assert "3,871,341 to 5,089,679 if they all miss the same way at once" in s
    assert s in trust_statement(hist)
    mixed = {"A": {"centre": "global_blend"}, "B": {"centre": "naive"}}
    assert "blend of the pooled model and TimesFM for 1 series" in panel_sentence(
        [{"kind": "tool", "tool": "forecast_report", "result": {"n_series": 2, "series": mixed}}])
    # a pack that shows only some of its series names no centre count, rather than a wrong one
    assert "centre line" not in panel_sentence(
        [{"kind": "tool", "tool": "forecast_report", "result": {"n_series": 60, "series": series}}])
